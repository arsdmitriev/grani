/**
 * The library's manifest: one entry per component. The package's text for language models
 * (`scripts/reference/text.mjs`), the gates and the showcase read it. The rules of behavior with
 * their proofs live in `scripts/reference/patterns.ts`; the showcase's own words (the logic
 * catalogue, where a pattern is shown) live with the showcase.
 *
 * level: `component` is one thing with an API, `block` assembles a screen from components,
 * `pattern` lays a way of behaving over a surface the library has.
 * status: `experimental` passed the machine gates (isolation, API vocabulary,
 * tests); `stable` also passed the UX and accessibility review by eye.
 * task: what a person is trying to do when they reach for the component.
 */
/** `component` is one thing with an API, used on its own; `block` is a finished piece of a screen assembled from components, owning no state; `pattern` is a way of behaving laid over a surface (a question over a window, commands over a popover). */
export type Level = 'component' | 'block' | 'pattern'
export type Status = 'experimental' | 'stable'
/** What a component is about; a family holds primitives, modules and blocks alike, and the showcase groups by it. */
export type Family =
  'data' | 'charts' | 'form' | 'dates' | 'actions' | 'overlay' | 'layout' | 'status'

export interface RegistryEntry {
  level: Level
  status: Status
  family: Family
  since: string
  /** A part of another component (a radio of a radio group): no page of its own, shown in the parent's reference and shipped in its registry item. */
  parent?: string
  /** A pattern: the surface it behaves over; that surface's page names the pattern. */
  over?: string
  /** The composables and utilities it is built on, by file name; the reference names them and the logic page lists who uses what. */
  logic?: string[]
  /** The other names people and search engines know it by, lowercase (`accordion` for UiReveal): the showcase's search, the component's page and the texts for agents say them; the API does not change. */
  aka?: string[]
}

