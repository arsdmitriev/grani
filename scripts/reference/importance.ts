/** A component's patterns in its own order, the rest after them by importance. */
export const orderOn = <R extends { key: string }>(name: string, rules: R[]): R[] => {
  const order = (ORDERS[name] ?? []) as string[]
  const named = order.flatMap((key) => rules.filter((r) => r.key === key))
  return [...named, ...rules.filter((r) => !order.includes(r.key))]
}
